func TestRank(t *testing.T) {
	t.Parallel()

	functions := []Function{
		{ID: "a", Calls: []string{"decode", "read"}, NodeCounts: map[string]int{ifStatement: 1, returnStmt: 2}},
		{ID: "b", Calls: []string{"decode", "write"}, NodeCounts: map[string]int{ifStatement: 1, returnStmt: 2}},
		{ID: "c", Calls: []string{"close"}, NodeCounts: map[string]int{"ForStmt": 1}},
	}
	embeddings := [][]float32{{1, 0}, {1, 0}, {0, 1}}
	candidates, err := Rank(functions, embeddings, 0.8, 10)
	if err != nil {
		t.Fatal(err)
	}
	if len(candidates) != 1 {
		t.Fatalf("got %d candidates, want 1", len(candidates))
	}
	candidate := candidates[0]
	if candidate.Left.ID != "a" || candidate.Right.ID != "b" {
		t.Fatalf("pair = %s, %s", candidate.Left.ID, candidate.Right.ID)
	}
	if candidate.StructureScore != 1 || candidate.CallScore != 1.0/3.0 {
		t.Fatalf("scores = %v, %v", candidate.StructureScore, candidate.CallScore)
	}
}

func TestRankKeepsAFunctionsOwnBestMatchAgainstHigherScoringPairs(t *testing.T) {
	t.Parallel()

	functions := []Function{{ID: "a"}, {ID: "b"}, {ID: "c"}, {ID: "d"}, {ID: "e"}}
	embeddings := [][]float32{
		{1, 0, 0, 0},
		{0.6, 0.8, 0, 0},
		{0, 0, 1, 0},
		{0, 0, 0.99, 0.141},
		{0, 0, 0.98, 0.199},
	}

	candidates, err := Rank(functions, embeddings, 0.5, 3)
	if err != nil {
		t.Fatal(err)
	}

	pairs := make([]string, 0, len(candidates))
	for _, candidate := range candidates {
		pairs = append(pairs, candidate.Left.ID+candidate.Right.ID)
	}
	if !slices.Contains(pairs, "ab") {
		t.Fatalf("pairs = %v, want the ab pair: a and b are each other's best match at 0.6, "+
			"and a cut on absolute score drops them behind the c, d, e cluster near 0.99", pairs)
	}
}

func TestSeparationMeasuresTheGapBelowEachNeighbour(t *testing.T) {
	t.Parallel()

	row := []neighbour{{score: 0.9}, {score: 0.5}, {score: 0.45}, {score: 0.4}}
	separate(row)

	if !(row[0].separation > row[1].separation) {
		t.Errorf("separations = %v, want the standout neighbour above the plateau", row)
	}
	if row[len(row)-1].separation != 0 {
		t.Errorf("last separation = %v, want 0: nothing follows it", row[len(row)-1].separation)
	}
}

func TestSeparationIgnoresTheScoreFloorWhenShapingTheDistribution(t *testing.T) {
	t.Parallel()

	functions := []Function{{ID: "a"}, {ID: "b"}, {ID: "c"}, {ID: "d"}}
	embeddings := [][]float32{
		{1, 0, 0},
		{0.8, 0.6, 0},
		{0.2, 0, 0.9797},
		{0.1, 0, 0.995},
	}

	candidates, err := Rank(functions, embeddings, 0.7, 10)
	if err != nil {
		t.Fatal(err)
	}
	if len(candidates) == 0 {
		t.Fatal("no candidates survived the floor")
	}
	for _, candidate := range candidates {
		if candidate.Separation == 0 {
			t.Errorf("pair %s/%s has no separation: the floor left too few neighbours to measure against",
				candidate.Left.ID, candidate.Right.ID)
		}
	}
}

func TestSequenceSimilaritySeparatesNestingThatCountsCannot(t *testing.T) {
	t.Parallel()

	outerIf := Function{
		NodeCounts:   map[string]int{ifStatement: 1, rangeStmt: 1, assignStmt: 1},
		NodeSequence: []string{ifStatement, rangeStmt, assignStmt},
	}
	outerRange := Function{
		NodeCounts:   map[string]int{ifStatement: 1, rangeStmt: 1, assignStmt: 1},
		NodeSequence: []string{rangeStmt, ifStatement, assignStmt},
	}
	if structure := histogramCosine(outerIf.NodeCounts, outerRange.NodeCounts); structure != 1 {
		t.Fatalf("node mix should not separate these, got %v", structure)
	}
	sequence := SequenceSimilarity(outerIf, outerRange)
	if sequence >= 1 {
		t.Fatalf("sequence score did not separate the pair, got %v", sequence)
	}
	identical := SequenceSimilarity(outerIf, outerIf)
	if identical != 1 {
		t.Fatalf("identical sequences scored %v", identical)
	}
}

