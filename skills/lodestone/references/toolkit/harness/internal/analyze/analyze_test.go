const (
	allPackages = "./..."
	ifStatement = "IfStmt"
	rangeStmt   = "RangeStmt"
	assignStmt  = "AssignStmt"
	returnStmt  = "ReturnStmt"
)

func moduleFixture(t *testing.T, sample string) string {
	t.Helper()

	root := t.TempDir()
	writeTestFile(t, filepath.Join(root, "go.mod"), "module example\n\ngo 1.26\n")
	writeTestFile(t, filepath.Join(root, "sample.go"), sample)

	return root
}

func scanFixture(t *testing.T, root string, includeGenerated bool) ScanResult {
	t.Helper()

	scanned, err := Scan(context.Background(), ScanOptions{
		Root:             root,
		Patterns:         []string{allPackages},
		MinLines:         4,
		IncludeGenerated: includeGenerated,
	})
	if err != nil {
		t.Fatal(err)
	}

	return scanned
}

func TestScan(t *testing.T) {
	t.Parallel()

	root := moduleFixture(t, `package example

type worker struct{}

func tiny() {}

func (worker) Run(value int) error {
	if value > 0 {
		return nil
	}
	return os.ErrInvalid
}
`)
	scanned := scanFixture(t, root, false)
	if len(scanned.Functions) != 1 {
		t.Fatalf("got %d functions, want 1", len(scanned.Functions))
	}
	function := scanned.Functions[0]
	if function.Name != "worker.Run" {
		t.Fatalf("name = %q", function.Name)
	}
	if function.File != "sample.go" || function.Line != 7 {
		t.Fatalf("location = %s:%d", function.File, function.Line)
	}
	if len(function.Calls) != 0 {
		t.Fatalf("calls = %v", function.Calls)
	}
	if function.NodeCounts[ifStatement] != 1 {
		t.Fatalf("nodes = %v", function.NodeCounts)
	}
}

func TestScanIncludesRepositoryTestsWithoutSyntheticFiles(t *testing.T) {
	t.Parallel()

	root := moduleFixture(t, `package example

func Production(value int) int {
	if value < 0 {
		return -value
	}
	return value
}
`)
	writeTestFile(t, filepath.Join(root, "sample_test.go"), `package example

import "testing"

func TestProduction(t *testing.T) {
	t.Parallel()
	if Production(-1) != 1 {
		t.Fatal("unexpected result")
	}
}
`)

	scanned, err := Scan(context.Background(), ScanOptions{
		Root: root, Patterns: []string{allPackages}, MinLines: 4, MinNodes: 3, IncludeTests: true,
	})
	if err != nil {
		t.Fatal(err)
	}

	names := make([]string, 0, len(scanned.Functions))
	for _, function := range scanned.Functions {
		names = append(names, function.Name)
		if !filepath.IsLocal(function.File) {
			t.Fatalf("non-local source was scanned: %s", function.File)
		}
	}
	if !slices.Contains(names, "Production") || !slices.Contains(names, "TestProduction") {
		t.Fatalf("functions = %v", names)
	}
}

func TestScanSkipsGeneratedFiles(t *testing.T) {
	t.Parallel()

	root := t.TempDir()
	writeTestFile(t, filepath.Join(root, "go.mod"), "module example\n\ngo 1.26\n")
	body := `
func Handle(value int) error {
	if value > 0 {
		return nil
	}
	return nil
}
`
	writeTestFile(t, filepath.Join(root, "hand.go"), "package example\n"+body)
	writeTestFile(
		t, filepath.Join(root, "wire.go"),
		"// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage example\n"+body,
	)
	scanned := scanFixture(t, root, false)
	if len(scanned.Functions) != 1 || scanned.Functions[0].File != "hand.go" {
		t.Fatalf("functions = %v", scanned.Functions)
	}
	if len(scanned.Generated) != 1 || scanned.Generated[0] != "wire.go" {
		t.Fatalf("generated = %v", scanned.Generated)
	}
	kept := scanFixture(t, root, true)
	if len(kept.Functions) != 2 || len(kept.Generated) != 0 {
		t.Fatalf("include-generated kept %d functions, %d generated", len(kept.Functions), len(kept.Generated))
	}
}

