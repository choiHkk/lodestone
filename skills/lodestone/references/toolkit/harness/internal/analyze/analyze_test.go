func TestFunctionSourceDropsInlineCommentsButKeepsDirectives(t *testing.T) {
	t.Parallel()

	root := moduleFixture(t, `package example

func Handle(value int) error {
	// this explanation should not reach the embedding
	if value > 0 {
		return nil // trailing note
	}
	//go:noinline
	return nil
}
`)
	scanned := scanFixture(t, root, false)
	if len(scanned.Functions) != 1 {
		t.Fatalf("functions = %v", scanned.Functions)
	}
	source := scanned.Functions[0].Source
	for _, dropped := range []string{"this explanation", "trailing note"} {
		if strings.Contains(source, dropped) {
			t.Fatalf("comment survived into the embedding text: %q", source)
		}
	}
	if !strings.Contains(source, "//go:noinline") {
		t.Fatalf("directive was stripped: %q", source)
	}
	if !strings.Contains(source, "if value > 0") {
		t.Fatalf("code was lost: %q", source)
	}
}

